export function storyBatch(lang, variant) {
  const index = languages.indexOf(lang);
  const person = people[variant % people.length];
  const day = Math.floor(variant / people.length);
  const time = times[day] || [
    'On day ' + (day + 1), (day + 1) + ' ஆம் நாள்', (day + 1) + 'ാം ദിവസം',
    (day + 1) + 'ನೇ ದಿನ', (day + 1) + 'వ రోజు',
  ];
  const fill = (text, language) => text.replaceAll('{name}', person[language]).replaceAll('{time}', time[language]);
  return stories.map(({ title, summary, scenes, alternateEnding }) => ({
    lang,
    level: 'A2',
    title: title[index] + ' · ' + person[index] + ' · ' + time[index],
    title_en: title[0] + ' · ' + person[0] + ' · ' + time[0],
    summary,
    category: 'short-story',
    paragraphs: (variant % 2 ? [...scenes.slice(0, -1), alternateEnding] : scenes)
      .map((scene) => ({ ta: fill(scene[index], index), en: fill(scene[0], 0) })),
    source_type: 'original',
    source_note: 'Original ChatGPT-assisted practice story assembled locally from a template.',
  }));
}
